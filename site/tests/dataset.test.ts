/**
 * dataset.test.ts — end-to-end over the REAL packed dataset.
 *
 * This is the most important test in the suite. Everything else verifies the TypeScript
 * against synthetic containers built by a third implementation in tests/helpers.ts. This
 * one verifies the TypeScript against the actual bytes that harvester/pack_binary.py
 * produced from 82 MB of real Indian Railways data — so it is what proves the Python
 * writer and the browser reader agree on the real thing, not just on a fixture.
 *
 * The assertions are concrete facts about the Indian network (Howrah Rajdhani runs
 * Howrah → New Delhi in 17 h over 8 stops), not tautologies about the code. If a packing
 * change silently scrambles the graph, this fails with a sentence a human can check
 * against a timetable.
 */
import { readFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { resolve } from 'node:path';
import { beforeAll, describe, expect, it } from 'vitest';
import { Container, ContainerKind, SectionId } from '../src/lib/binary';
import {
  Graph, stationCountOf, decodeRunsDays, fmtWallClock,
} from '../src/lib/graph';
import { StationIndex } from '../src/lib/stations';
import type { DatasetManifest } from '../src/state/cache';

const DATA = resolve(__dirname, '../public/data');
const HAVE_DATA = existsSync(resolve(DATA, 'stations.bin')) && existsSync(resolve(DATA, 'graph.bin'));

function readAb(file: string): ArrayBuffer {
  const b = readFileSync(resolve(DATA, file));
  return b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength) as ArrayBuffer;
}

let manifest: DatasetManifest;
let stations: StationIndex;
let graph: Graph;

beforeAll(() => {
  manifest = JSON.parse(readFileSync(resolve(DATA, 'manifest.json'), 'utf8')) as DatasetManifest;
  const sc = Container.parse(readAb('stations.bin'), ContainerKind.Stations);
  stations = StationIndex.fromContainer(sc);
  const gc = Container.parse(readAb('graph.bin'), ContainerKind.Graph);
  stations.attachGeo(gc);
  graph = Graph.fromContainer(gc, stationCountOf(gc));
});

describe.skipIf(!HAVE_DATA)('packed dataset', () => {
  it('exists and matches its manifest', () => {
    expect(HAVE_DATA).toBe(true);
    expect(stations.count).toBe(manifest.counts.stations);
    expect(graph.trainCount).toBe(manifest.counts.trains);
    expect(graph.connCount).toBe(manifest.counts.connections);
  });

  it('is flagged as bootstrap so the UI shows "BOOTSTRAP · 2016"', () => {
    // Without this bit the app would present a 2016 timetable as current, which is the
    // single most serious way this product could mislead someone.
    expect(stations.isBootstrap).toBe(true);
    expect(graph.isBootstrap).toBe(true);
    expect(manifest.bootstrap).toBe(true);
    expect(manifest.bootstrapLabel).toBe('BOOTSTRAP · 2016');
    expect(graph.runsDaysAllAssumed).toBe(true);
  });

  it('keeps first paint inside the 120 KB budget', () => {
    const gz = manifest.files['stations.bin'].gzipBytes;
    expect(gz).toBeLessThan(120 * 1024);
    expect(gz).toBeGreaterThan(10 * 1024);   // and not suspiciously empty
  });

  it('keeps every file far below the GitHub Pages 50 MB warning threshold', () => {
    for (const [name, f] of Object.entries(manifest.files)) {
      expect(f.bytes, name).toBeLessThan(50 * 1024 * 1024);
    }
  });

  it('matches the sha256 recorded in its own manifest', () => {
    // Guards against a binary being edited or half-regenerated by hand and committed
    // without the manifest. CI has no other way to tell: the file parses fine, it just is
    // not the file the harvester produced.
    for (const [name, meta] of Object.entries(manifest.files)) {
      const bytes = readFileSync(resolve(DATA, name));
      const got = createHash('sha256').update(bytes).digest('hex');
      expect(got, `${name} sha256`).toBe(meta.sha256);
      expect(bytes.byteLength, `${name} size`).toBe(meta.bytes);
    }
  });

  it('declares no section that needs a u32 where a u16 was packed', () => {
    // Station indices are u16 in every record. If a future harvest pushes the network
    // past 65,536 stations the packer must widen the format, and this is the tripwire.
    expect(stations.count).toBeLessThan(0x10000);
    expect(manifest.limits.maxLegsPerTrain).toBeLessThan(0x10000);
    expect(manifest.limits.maxDurationMin).toBeLessThan(0x10000);
    expect(manifest.limits.maxDistanceKm).toBeLessThan(0x10000);
  });
});

describe.skipIf(!HAVE_DATA)('real stations', () => {
  it('finds Hyderabad Deccan by name', () => {
    expect(stations.search('hyderabad', 8).map((s) => s.code)).toContain('HYB');
  });

  it('does NOT know that Secunderabad and Kacheguda are Hyderabad terminals', () => {
    // Documents a real gap rather than asserting a capability we do not have. The 2016
    // source carries no city->station mapping, so searching "hyderabad" cannot surface SC
    // or KCG -- only HYB, whose NAME contains the word. Closing this needs a city index
    // (Phase 3 discovery work); until then a Hyderabad user must know to type
    // "Secunderabad". Asserting the current behaviour keeps the gap visible and turns
    // this test into a marker that fires the day it is fixed.
    const codes = stations.search('hyderabad', 20).map((s) => s.code);
    expect(codes).not.toContain('SC');
    expect(codes).not.toContain('KCG');
    expect(stations.search('secunderabad', 5).map((s) => s.code)).toContain('SC');
    expect(stations.search('kacheguda', 5).map((s) => s.code)).toContain('KCG');
  });

  it('finds a station by its code', () => {
    expect(stations.search('ndls')[0]?.name).toMatch(/New Delhi/i);
    expect(stations.byCodeLookup('HWH')?.name).toMatch(/Howrah/i);
  });

  it('ranks major junctions above halts', () => {
    // These are genuinely among India's busiest stations; a halt with two trains a day
    // must not outrank them in a suggestion list.
    for (const code of ['NDLS', 'HWH', 'SC', 'CNB', 'BZA']) {
      const s = stations.byCodeLookup(code);
      expect(s, code).toBeDefined();
      expect(s!.rank, `${code} rank`).toBeGreaterThanOrEqual(2);
    }
    const metros = stations.popular(50).filter((s) => s.rank === 3);
    expect(metros.length).toBeGreaterThan(0);
  });

  it('offers recognisable hubs as the default suggestions', () => {
    const top = stations.popular(12).map((s) => s.code);
    // Kanpur Central, Howrah, Vijayawada, New Delhi and Secunderabad are all in the real
    // top-15 by number of trains calling.
    expect(top.filter((c) => ['CNB', 'HWH', 'BZA', 'NDLS', 'SC'].includes(c)).length)
      .toBeGreaterThanOrEqual(3);
  });

  it('carries plausible coordinates for every station', () => {
    expect(stations.hasGeo).toBe(true);
    let checked = 0;
    for (let i = 0; i < stations.count; i++) {
      const s = stations.at(i);
      expect(s.lat, s.code).toBeGreaterThan(5);
      expect(s.lat, s.code).toBeLessThan(39);
      expect(s.lon, s.code).toBeGreaterThan(66);
      expect(s.lon, s.code).toBeLessThan(99);
      checked++;
    }
    expect(checked).toBe(stations.count);
  });

  it('has no station in the index that no train ever calls at', () => {
    // A dead-end station in autocomplete means the user can pick an origin they can never
    // leave. The normaliser prunes these; this asserts the pruning held.
    let orphans = 0;
    for (let i = 0; i < stations.count; i++) {
      if (stations.at(i).calls === 0) orphans++;
    }
    expect(orphans).toBe(0);
  });
});

describe.skipIf(!HAVE_DATA)('real trains', () => {
  function findByNumber(num: string) {
    for (let t = 0; t < graph.trainCount; t++) {
      if (graph.train(t).number === num) return t;
    }
    return -1;
  }

  it('decodes the Howrah Rajdhani correctly', () => {
    const t = findByNumber('12301');
    expect(t).toBeGreaterThanOrEqual(0);
    const train = graph.train(t);

    expect(train.name).toMatch(/Howrah.*Rajdhani/i);
    // Brand detected from the NAME: the source's own type column says "Exp".
    expect(train.type).toBe('RAJ');
    expect(train.classes).toEqual(['1A', '2A', '3A']);

    const stops = graph.rawStopsOfTrain(t);
    expect(stops[0].station).toBe(train.origin);
    expect(stops.at(-1)!.station).toBe(train.destination);
    expect(stations.at(train.origin).code).toBe('HWH');
    expect(stations.at(train.destination).code).toBe('NDLS');

    // Real 12301: departs Howrah 16:55, reaches New Delhi 09:55 next day, 8 stops.
    expect(stops).toHaveLength(8);
    expect(train.durationMin).toBe(1020);
    expect(train.originDepMin).toBe(16 * 60 + 55);
    expect(fmtWallClock(train.originDepMin, 0)).toBe('16:55');
    expect(fmtWallClock(train.originDepMin, stops.at(-1)!.arrMin)).toBe('09:55 +1d');

    // It genuinely calls at Dhanbad, Gaya, DDU, Prayagraj and Kanpur.
    const codes = stops.map((s) => stations.at(s.station).code);
    for (const expected of ['DHN', 'GAYA', 'DDU', 'PRYJ', 'CNB']) {
      expect(codes, `12301 should call at ${expected}`).toContain(expected);
    }
    // ...and its cumulative distance ends near the official 1,447 km.
    expect(train.distanceKm).toBeGreaterThan(1300);
    expect(train.distanceKm).toBeLessThan(1650);
  });

  it('keeps stops monotonic in time and distance across the whole network', () => {
    let badTime = 0;
    let badDist = 0;
    for (let t = 0; t < graph.trainCount; t++) {
      const stops = graph.rawStopsOfTrain(t);
      for (let k = 1; k < stops.length; k++) {
        const prevDep = stops[k - 1].depMin;
        const arr = stops[k].arrMin;
        if (prevDep !== null && arr !== null && arr < prevDep) badTime++;
        if (stops[k].distKm < stops[k - 1].distKm) badDist++;
      }
    }
    expect(badTime).toBe(0);
    expect(badDist).toBe(0);
  });

  it('keeps every arrival at or after its own departure', () => {
    let bad = 0;
    for (let c = 0; c < graph.connCount; c++) {
      const leg = graph.leg(c);
      if (leg.arrMin < leg.depMin) bad++;
    }
    expect(bad).toBe(0);
  });

  it('accounts for every connection in exactly one train block', () => {
    let total = 0;
    let prevEnd = 0;
    for (let t = 0; t < graph.trainCount; t++) {
      const tr = graph.train(t);
      // Blocks must be contiguous and ordered, or trainOfConnection's binary search lies.
      expect(tr.connStart, `train ${tr.number}`).toBe(prevEnd);
      total += tr.legCount;
      prevEnd = tr.connStart + tr.legCount;
    }
    expect(total).toBe(graph.connCount);
  });

  it('resolves the owning train for every connection', () => {
    for (let t = 0; t < graph.trainCount; t++) {
      const tr = graph.train(t);
      expect(graph.trainOfConnection(tr.connStart)).toBe(t);
      expect(graph.trainOfConnection(tr.connStart + tr.legCount - 1)).toBe(t);
    }
    expect(graph.trainOfConnection(graph.connCount)).toBe(-1);
  });

  it('balances the adjacency transpose against the connection count', () => {
    let deps = 0;
    let arrs = 0;
    for (let s = 0; s < stations.count; s++) {
      deps += graph.departuresFrom(s).length;
      arrs += graph.arrivalsAt(s).length;
    }
    // Every connection leaves exactly one station and arrives at exactly one.
    expect(deps).toBe(graph.connCount);
    expect(arrs).toBe(graph.connCount);
  });

  it('flags the whole dataset as having assumed running days', () => {
    expect(graph.runsDaysAllAssumed).toBe(true);
  });

  it('marks running days as assumed, never as fact', () => {
    // The 2016 source has no runs_days column. Presenting "Daily" without the caveat
    // would send someone to a platform for a train that runs only on Tuesdays.
    let assumed = 0;
    for (let t = 0; t < graph.trainCount; t++) {
      const tr = graph.train(t);
      expect(decodeRunsDays(tr.runsDays)).toBe('Daily');
      if (tr.runsDaysAssumed) assumed++;
    }
    expect(assumed).toBe(graph.trainCount);
  });

  it('gives every train at least one bookable class', () => {
    for (let t = 0; t < graph.trainCount; t++) {
      const tr = graph.train(t);
      expect(tr.classes.length, `${tr.number} ${tr.name}`).toBeGreaterThan(0);
    }
  });

  it('finds real services through a major junction', () => {
    const sc = stations.byCodeLookup('SC');
    expect(sc).toBeDefined();
    const trains = graph.trainsAt(sc!.i);
    expect(trains.length).toBeGreaterThan(100);
    // Secunderabad is on the Delhi–Chennai trunk route, so both directions must appear.
    const names = trains.map((t) => graph.train(t).name.toLowerCase());
    expect(names.some((n) => n.includes('delhi') || n.includes('ndls'))).toBe(true);
    expect(names.some((n) => n.includes('chennai') || n.includes('madras'))).toBe(true);
  });

  it('keeps journey durations and speeds physically plausible', () => {
    let over = 0;
    for (let t = 0; t < graph.trainCount; t++) {
      const tr = graph.train(t);
      expect(tr.durationMin).toBeGreaterThan(0);
      if (tr.durationMin > 130 * 60) over++;
      if (tr.distanceKm > 0 && tr.durationMin > 15) {
        const kmh = tr.distanceKm / (tr.durationMin / 60);
        expect(kmh, `${tr.number} averages ${kmh.toFixed(0)} km/h`).toBeLessThan(160);
      }
    }
    expect(over).toBe(0);
  });
});

describe.skipIf(!HAVE_DATA)('section hygiene', () => {
  it('has no unused bytes beyond 4-byte alignment padding', () => {
    const gc = Container.parse(readAb('graph.bin'), ContainerKind.Graph);
    let declared = 0;
    for (const id of [SectionId.Strings, SectionId.StationGeo, SectionId.Trains, SectionId.Connections]) {
      declared += gc.section(id).length;
    }
    // Header + directory + sections + at most 3 bytes of padding per section.
    expect(gc.buffer.byteLength).toBeLessThanOrEqual(32 + 4 * 20 + declared + 12);
    expect(gc.buffer.byteLength).toBeGreaterThanOrEqual(32 + 4 * 20 + declared);
  });
});
